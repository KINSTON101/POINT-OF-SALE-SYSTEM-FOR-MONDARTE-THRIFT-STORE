    private void loginmainjbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginmainjbtnActionPerformed
      String user = txtlogin_username.getText().trim();
String pin = new String(pflogin_showpasspin.getPassword()).trim(); 

if (user.isEmpty() && pin.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please Enter username and PIN!", "Warning", JOptionPane.WARNING_MESSAGE);
} else if (user.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please Input username!", "Warning", JOptionPane.WARNING_MESSAGE);
} else if (pin.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please Input PIN!", "Warning", JOptionPane.WARNING_MESSAGE);
} 
else if (pin.length() != 4 || !pin.matches("\\d+")) {
    JOptionPane.showMessageDialog(this, "PIN must be exactly 4 digits long!", "Input Error", JOptionPane.WARNING_MESSAGE);
}
else {
    try (Connection conn = thriftstore_pointofsale_system.DBConnection2.connect()) {
        
       
        String adminSql = "SELECT admin_id, admin_username FROM tbl_admin_info WHERE UPPER(admin_username) = UPPER(?) AND admin_pin = ?";
        
        try (PreparedStatement adminStmt = conn.prepareStatement(adminSql)) {
            adminStmt.setString(1, user);
            adminStmt.setString(2, pin);
            
            try (ResultSet adminRs = adminStmt.executeQuery()) {
                if (adminRs.next()) {
                    int adminId = adminRs.getInt("admin_id");
                    String adminUser = adminRs.getString("admin_username");

                    
                    thriftstore_pointofsale_system.UserSession2.setUser(adminId, adminUser);

                    JOptionPane.showMessageDialog(this, "Login Successful! Welcome Admin " + adminUser + "!");
                    
                    
                    new Pos_admin1().setVisible(true);
                    this.dispose();
                    return; 
                }
            }
        }

        
        String staffSql = "SELECT user_id, username, role FROM tbl_staff_info WHERE UPPER(username) = UPPER(?) AND pin = ?";
        
        try (PreparedStatement staffStmt = conn.prepareStatement(staffSql)) {
            staffStmt.setString(1, user);
            staffStmt.setString(2, pin);
            
            try (ResultSet staffRs = staffStmt.executeQuery()) {
                if (staffRs.next()) {
                    int id = staffRs.getInt("user_id");
                    String dbUsername = staffRs.getString("username");
                    String role = staffRs.getString("role");

                    thriftstore_pointofsale_system.UserSession2.setUser(id, dbUsername);

                    JOptionPane.showMessageDialog(this, "Login Successful! Welcome " + role + "!");
                    
                    if ("ADMIN".equalsIgnoreCase(role)) {                 
                        new Pos_admin1().setVisible(true);
                    } else {                 
                        new Pos_terminal().setVisible(true);
                    }
                    this.dispose();
                    return;
                }
            }
        }

       
        JOptionPane.showMessageDialog(this, "Invalid Username or PIN!", "Warning", JOptionPane.WARNING_MESSAGE);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Database Connection Error: " + e.getMessage());
    }


}                                           
         

    }//GEN-LAST:event_loginmainjbtnActionPerformed

