// 3. KEYBOARD VALIDATION LISTENER (Pugong sa mga letters ug limit sa 4 digits)
pflogin_showpasspin.addKeyListener(new java.awt.event.KeyAdapter() {
    @Override
    public void keyTyped(java.awt.event.KeyEvent evt) {
        char c = evt.getKeyChar();
        
        // Kuhaa ang kasamtangang text o kung placeholder pa ba
        String currentText = new String(pflogin_showpasspin.getPassword());
        if (currentText.equals("Enter PIN")) {
            pflogin_showpasspin.setText("");
            pflogin_showpasspin.setEchoChar('•');
            pflogin_showpasspin.setForeground(java.awt.Color.BLACK);
            currentText = ""; // I-reset ang string para sa accurate length checking sunod
        }
        
        // Kung dili numero (digit) ug dili backspace, i-block o i-consume kini
        if (!Character.isDigit(c) && c != '\b') {
            evt.consume(); // Dili niya i-apil o i-dawat ang gi-type nga letra gikan sa physical keyboard
        }
        
        // Limitahan sa 4 ka numero ang PIN length
        if (currentText.length() >= 4 && c != '\b') {
            evt.consume();
        }
    }
});   
                     
        
